"""Workers: an interactive Pi in a tmux window (pipeline.workers-in-tmux, jailed-agent), messages to it (`tell`), and
what the runner reads back from its session JSONL (cost, tool calls, idleness; pipeline.cost-cap, messages).
The runner never holds a key: the worker wrapper reads the key file into the one env var Pi expects. The worker's
environment carries no runner path: its MCP server is a generated wrapper on PATH, under the state dir.
Ruled 2026-10-25: the runner runs on the Anthropic API through Pi; the claude-code kind is parked on its branch.

Known gap (pipeline.jailed-agent [PARTIAL]): the worker runs as the same user as the runner, so a shell inside it
can read the generated wrapper and reach the journal; until a write jail exists, the role split is a convention
the CLI and MCP enforce, not a boundary."""
from __future__ import annotations

import importlib.util
import json
import os
import re
import subprocess
import sys
import time
from collections import Counter
from pathlib import Path

from pipeline import ROOT, STATE
from pipeline.config import pi_model_id

WRAPPER = ROOT / "pipeline" / "pi-agent" / "run-worker.sh"
# USER/LOGNAME/SHELL/TMPDIR carry no secret and Claude Code needs them to find its Max login in the keychain
# (without USER it says "Not logged in", seen live 2026-10-25)
ALLOWED_ENV = ("PATH", "HOME", "TERM", "LANG", "USER", "LOGNAME", "SHELL", "TMPDIR")
ADAPTER_DIR = Path.home() / ".local" / "bin"


def sh(args: list[str], **kw) -> subprocess.CompletedProcess:
    return subprocess.run(args, capture_output=True, text=True, **kw)


def mcp_bin(task: str, role: str) -> Path:
    """A per-task bin dir under the state dir holding `pipeline-mcp`, which knows the runner's python, root and
    state; it goes on the worker's PATH so the worker env itself names no runner path."""
    d = STATE / "bin" / task / role  # one path per role: the reviewer never overwrites the coder's wrapper (#6145)
    d.mkdir(parents=True, exist_ok=True)
    w = d / "pipeline-mcp"
    # the wrapper carries the runner's state path: a runner started with PIPELINE_STATE set must get its done/ask
    # lines in ITS journal (first live run: the server fell back to the default and the runner never saw them). The
    # worker's env still names no state path; the role split stays a convention until the write jail exists
    w.write_text("#!/bin/bash\n# generated by the runner: the worker's MCP server (report/ask/done or verdict)\n"
                 f"export PYTHONPATH={ROOT} PIPELINE_ROOT={ROOT} PIPELINE_STATE={STATE} PIPELINE_WORKER={role}\n"
                 f"exec {sys.executable} -m pipeline.mcp_server --role {role}\n")
    w.chmod(0o700)
    return d


# The one short tool list, in one order, for every worker role (pipeline.batch-session, prompt-cache). The adapter's
# `mcp` proxy tool stays: it is the wide set, and every call to it is journaled as a brief miss.
SMALL_TOOLS = {"jcodemunch": ["search_symbols", "get_file_outline", "get_symbol_source", "find_references"],
               "jdocmunch": ["search_sections", "get_section"],
               "pipeline": ["report", "ask", "done", "verdict"]}


def mcp_config(cfg: dict, d: Path, docs: bool) -> Path:
    """The worker's MCP config, written next to its wrapper: the agent dir's servers, each with only its small
    tools direct; jdocmunch only when the brief cites docs (the first run exposed 146 tools)."""
    servers = json.loads((ROOT / cfg["workers"]["agent_dir"] / "mcp.json").read_text())["mcpServers"]
    out = {k: dict(servers[k], directTools=v) for k, v in SMALL_TOOLS.items() if k in servers and (docs or k != "jdocmunch")}
    p = d / "mcp.json"
    p.write_text(json.dumps({"mcpServers": out}, indent=1))
    return p


def require_mcp_sdk() -> None:
    """The worker's report/ask/done tools are served by the runner's python: no MCP SDK there must stop `start`,
    not leave a worker without its done tool (first live run, 2026-10-25)."""
    if importlib.util.find_spec("mcp") is None:
        raise RuntimeError(f"{sys.executable} cannot import the MCP SDK (`mcp`): the worker would have no done/ask "
                           "tools; run the runner with the repo venv's python")


def allowed_env(cfg: dict, task: str = "", role: str = "coder") -> dict:
    """The worker's environment: PATH, HOME, TERM, LANG, Pi's agent dir and the worker mark; the key is added by
    the wrapper. No PIPELINE_ROOT/STATE/PYTHON: those live in the generated wrapper on PATH."""
    env = {k: os.environ[k] for k in ALLOWED_ENV if k in os.environ}
    agent = ROOT / cfg["workers"]["agent_dir"]
    env["PI_CODING_AGENT_DIR"] = str(agent)
    env["PIPELINE_WORKER"] = role  # the CLI refuses verdict/answer when it sees this
    bins = [str(mcp_bin(task, role))] if task else []
    env["PATH"] = ":".join(bins + [str(ADAPTER_DIR), env.get("PATH", "/usr/bin:/bin")])
    return env


def key_source(cfg: dict, worker: dict) -> tuple[str, str]:
    """(env var, key file) for the worker's provider; the lane key file wins when it exists; never read here."""
    k = cfg["keys"].get(worker["provider"], {"env": "", "files": []})
    for f in k["files"]:
        if Path(f).expanduser().exists():
            return k["env"], str(Path(f).expanduser())
    return k["env"], ""


def pi_command(cfg: dict, worker: dict, session_dir: Path, role: str = "coder", task: str = "", docs: bool = False) -> list[str]:
    """Interactive Pi with only the MCP adapter (the small tool set when a task is given), the project's shared
    principles and the role's ponytail rules."""
    agent = ROOT / cfg["workers"]["agent_dir"]
    env_var, key_file = key_source(cfg, worker)
    cmd = [str(WRAPPER), env_var or "-", key_file or "-", "pi",
           "--no-extensions", "-e", str(Path(cfg["workers"]["pi_adapter"]).expanduser()),
           *(["--mcp-config", str(mcp_config(cfg, mcp_bin(task, role), docs))] if task else []),
           # no AGENTS.md/CLAUDE.md: 68 KB (~17k tokens) per turn and a "read STATE.md first" that sends a worker
           # exploring; the brief and the role's rules are the whole prompt
           "--no-skills", "--no-prompt-templates", "--no-themes", "--no-context-files",
           "--session-dir", str(session_dir), "--model", pi_model_id(worker)]
    for f in sorted((agent / "skills" / "_shared").glob("*.md")) + [agent / "rules" / f"ponytail-{role}.md"]:
        cmd += ["--append-system-prompt", str(f)]
    return cmd


def ask_once(cfg: dict, worker: dict, prompt: str, session_dir: Path) -> dict:
    """One non-interactive call (pi -p, no tools, no context files) through the key wrapper: the session's status
    (cost, tokens) plus `answer`, the model's text."""
    env_var, key_file = key_source(cfg, worker)
    session_dir.mkdir(parents=True, exist_ok=True)
    cmd = [str(WRAPPER), env_var or "-", key_file or "-", "pi", "-p", "--no-tools", "--no-extensions", "--no-skills",
           "--no-prompt-templates", "--no-themes", "--no-context-files", "--session-dir", str(session_dir),
           "--model", pi_model_id(worker), prompt]
    try:
        r = sh(["env", "-i", *[f"{k}={v}" for k, v in allowed_env(cfg).items()], *cmd], timeout=300)
        answer = r.stdout
    except subprocess.TimeoutExpired:
        answer = ""
    return dict(status(session_dir), answer=answer)


def window_env_args(env: dict) -> list[str]:
    return [a for k, v in env.items() for a in ("-e", f"{k}={v}")]


def _session(cfg: dict) -> str:
    return cfg["workers"]["tmux_session"]


def live_windows(cfg: dict) -> set[str]:
    r = sh(["tmux", "list-windows", "-t", _session(cfg), "-F", "#{window_name}"])
    return set(r.stdout.split()) if r.returncode == 0 else set()


def start_window(cfg: dict, name: str, cwd: Path, cmd: list[str], env: dict) -> None:
    """One tmux session for the pipeline; one window per worker, started with ONLY the allow-listed env."""
    session = _session(cfg)
    if sh(["tmux", "has-session", "-t", session]).returncode:
        sh(["tmux", "new-session", "-d", "-s", session, "-n", "jobs", "-c", str(ROOT)])
    sh(["tmux", "kill-window", "-t", f"{session}:{name}"])
    r = sh(["tmux", "new-window", "-d", "-t", session, "-n", name, "-c", str(cwd), *window_env_args(env),
            "env", "-i", *[f"{k}={v}" for k, v in env.items()], *cmd])
    if r.returncode:
        raise RuntimeError(f"tmux new-window: {r.stderr.strip()}")
    time.sleep(10)  # ponytail: Pi's TUI takes a few seconds to accept input; a readiness probe when this bites


def stop_window(cfg: dict, name: str) -> None:
    """Stop a worker: interrupt its turn, give it a moment, then kill the window (pipeline.cost-cap)."""
    target = f"{_session(cfg)}:{name}"
    sh(["tmux", "send-keys", "-t", target, "Escape"])
    time.sleep(3)
    sh(["tmux", "kill-window", "-t", target])


def tell(cfg: dict, window: str, text: str, session_dir: Path | None = None, wait_s: float = 30.0) -> bool:
    """Lifted from agent-work/status/briefs/tell.sh: type the text, pause, C-m. One line; long text is a brief file.
    The send is not trusted (2026-10-25: three lanes sat idle for hours with the text left in the input box): with a
    session dir, delivery is confirmed by a NEW user turn in the log within `wait_s`; until then C-m is sent again,
    up to three times. Returns whether the turn appeared (True when there is no log to confirm against)."""
    target = f"{_session(cfg)}:{window}"
    before = status(session_dir)["prompts"] if session_dir else None
    STATE.mkdir(parents=True, exist_ok=True)
    with open(STATE / f"window-{window}.lock", "a"):  # ponytail: the lock file exists; serialising typists is Stage 1
        sh(["tmux", "send-keys", "-t", target, "-l", text])
        time.sleep(1)
        sh(["tmux", "send-keys", "-t", target, "C-m"])
        if session_dir is None:
            return True
        deadline = time.time() + wait_s
        for resend in range(4):
            while time.time() < deadline:
                if status(session_dir)["prompts"] > before:
                    return True
                time.sleep(2)
            if resend < 3:
                sh(["tmux", "send-keys", "-t", target, "C-m"])
                deadline = time.time() + wait_s / 3
    return False


def brief_file(task: str, name: str, text: str) -> Path:
    p = STATE / "briefs" / task / f"{name}.md"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)
    return p


# --- reading the session log ---------------------------------------------------------------------------------

EMPTY = {"cost_usd": 0.0, "tokens": 0, "tool_calls": Counter(), "idle": False, "last_text": "", "rate_limited": False,
         "model": "", "turns": 0, "prompts": 0, "started": False, "error": "", "transient": False,
         "cache_read": 0, "cache_write": 0, "fresh": 0, "cache_hit": 0.0, "proxy_calls": 0}


def cache_hit(s: dict) -> float:
    """Cached-read tokens over all prompt tokens read this session (the page's hit rate)."""
    total = s["cache_read"] + s["cache_write"] + s["fresh"]
    return round(s["cache_read"] / total, 3) if total else 0.0
QUOTA = re.compile(r"\b(402|429|rate.?limit|usage limit|insufficient|quota|credit)|limit reached|hit your (\w+ )?limit|resets \d", re.I)
TRANSIENT = re.compile(r"\b5\d\d\b|overloaded|timed? ?out|temporarily|connection", re.I)  # passing: back off, then look again
TRANSIENT_RETRIES = 4


def session_files(session_dir: Path) -> list[Path]:
    return sorted(session_dir.glob("*.jsonl"), key=lambda p: p.stat().st_mtime) if session_dir.exists() else []


def parse_session(path: Path) -> dict:
    """cost_usd, tokens, tool_calls (Counter by name), turns (assistant messages), idle, last_text, rate_limited,
    model — from a Pi JSONL, or a Claude Code JSONL (no price; usage limit => rate_limited). A session with no
    assistant turn is not idle: it has not answered anything yet."""
    out = dict(EMPTY, tool_calls=Counter(), started=True)
    for line in path.read_text().splitlines():
        try:
            o = json.loads(line)
        except ValueError:
            continue
        m = o.get("message") if isinstance(o.get("message"), dict) else None
        if not m or not isinstance(m.get("content"), (list, str)):
            continue
        role = m.get("role") or o.get("type")
        content = m["content"] if isinstance(m["content"], list) else [{"type": "text", "text": m["content"]}]
        if role == "assistant":
            out["turns"] += 1
            u = m.get("usage") or {}
            out["cost_usd"] += ((u.get("cost") or {}).get("total") or 0.0)
            out["tokens"] += u.get("totalTokens") or sum(u.get(k, 0) or 0 for k in (
                "input_tokens", "output_tokens", "cache_read_input_tokens", "cache_creation_input_tokens"))
            # cached tokens, provider-neutral (pipeline.prompt-cache): Pi's cacheRead/cacheWrite, Anthropic's
            # cache_read/cache_creation, OpenRouter's prompt_tokens_details.cached_tokens; a provider that reports none => 0
            details = u.get("prompt_tokens_details") or {}
            out["cache_read"] += u.get("cacheRead") or u.get("cache_read_input_tokens") or details.get("cached_tokens") or 0
            out["cache_write"] += u.get("cacheWrite") or u.get("cache_creation_input_tokens") or 0
            out["fresh"] += u.get("input") or u.get("input_tokens") or u.get("prompt_tokens") or 0
            out["model"] = m.get("model") or out["model"]
            stop = m.get("stopReason") or m.get("stop_reason") or ""
            out["idle"] = stop in ("stop", "end_turn", "endTurn", "stop_sequence") and not any(
                c.get("type") in ("toolCall", "tool_use") for c in content)
            # a quota or credit failure is read ONLY from structured error shapes of the LATEST turn (Pi: stopReason
            # "error" + errorMessage; Claude Code: isApiErrorMessage), never from what the model wrote (review MED C)
            # Claude Code reports a limit as an isApiErrorMessage line, or as a `<synthetic>`-model turn with the limit
            # wording ("5-hour limit reached ∙ resets 2am", "You've hit your limit"); both count, prose from a real turn never
            synthetic = o.get("isApiErrorMessage") or m.get("model") == "<synthetic>"
            err = m.get("errorMessage") if stop == "error" else (m.get("content") if synthetic else "")
            out["rate_limited"] = bool(err) and bool(QUOTA.search(str(err)))
            out["error"] = str(err)[:300] if err and not out["rate_limited"] else ""  # any other API error, latest turn
            out["transient"] = bool(out["error"]) and bool(TRANSIENT.search(out["error"]))
            for c in content:
                if c.get("type") in ("toolCall", "tool_use"):
                    name, args = c.get("name", "?"), c.get("arguments") or c.get("input") or {}
                    if name == "mcp" and isinstance(args, dict):  # the adapter's generic call: the real tool is inside
                        name = args.get("tool") or f"mcp:{args.get('server', '?')}"
                        out["proxy_calls"] += 1  # the wide set: a brief miss
                    out["tool_calls"][name] += 1
                elif c.get("type") == "text" and c.get("text"):
                    out["last_text"] = c["text"]
        elif role == "user":
            out["idle"] = False  # a prompt or a tool result is in, the answer is not
            # a human prompt is a string or a text block; Claude Code also files tool results as `user` lines
            if isinstance(m["content"], str) or any(c.get("type") == "text" for c in content) and not any(
                    c.get("type") == "tool_result" for c in content):
                out["prompts"] += 1
    out["cache_hit"] = cache_hit(out)
    return out


def status(session: Path) -> dict:
    """The worker's session: a Pi session dir (newest .jsonl in it) or one Claude Code session file."""
    session = Path(session)
    if session.suffix == ".jsonl":
        return parse_session(session) if session.exists() else dict(EMPTY, tool_calls=Counter())
    files = session_files(session)
    return parse_session(files[-1]) if files else dict(EMPTY, tool_calls=Counter())


def wait_idle(session_dir: Path, cap_usd: float, after_turns: int = 0, poll: float = 10.0, timeout_s: float = 3600,
              note=None, token_cap: int | None = None) -> dict:
    """Block until the worker has ANSWERED the message (more assistant turns than before the tell) and its last
    turn ended with no tool pending — or the cost cap (dollars, or tokens for a Max worker) is hit, or the time is up
    (then `stopped` says why)."""
    t0, transient_seen = time.time(), 0
    while True:
        s = status(session_dir)
        if s["started"] and s["cost_usd"] > cap_usd:
            s["stopped"] = f"cost cap: ${s['cost_usd']:.2f} > ${cap_usd:.2f}"
            return s
        if s["started"] and token_cap and s["tokens"] > token_cap:
            s["stopped"] = f"token cap: {s['tokens']} > {token_cap} tokens incl. cache"
            return s
        if s["rate_limited"] or (s["idle"] and s["turns"] > after_turns):
            return s
        if s.get("error") and s["turns"] > after_turns:
            if s.get("transient") and transient_seen < TRANSIENT_RETRIES:  # 5xx, overloaded, timeout: back off, look again
                from pipeline import budget
                time.sleep(budget.backoff(transient_seen))
                transient_seen += 1
                continue
            s["stopped"] = f"API error: {s['error']}"  # a 4xx other than 402/429, or a transient one that stayed
            return s
        if time.time() - t0 > timeout_s:
            s["stopped"] = f"no idle turn in {int(timeout_s)} s"
            return s
        if note:
            note(s)
        time.sleep(poll)


def uses_tools(s: dict, *prefixes: str) -> dict:
    return {p: sum(n for name, n in s["tool_calls"].items() if p in name) for p in prefixes}
