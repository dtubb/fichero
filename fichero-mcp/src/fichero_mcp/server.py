"""Fichero MCP server — the engine's OpenAPI contract as MCP tools.

Every tool comes from the contract (#5453): ``openapi_tools_generated.py`` holds one tool per
engine operation, generated by ``fichero-server/scripts/generate_openapi_mcp.py`` exactly as the
CLI is, and each makes one ``FicheroClient.request`` call. Adding a route adds its tool.

An agent picks **toolsets** (OpenAPI tags) at start with ``--toolsets``, so it sees the tools for
its job and not all of them. The default is the recipe golden path (``DEFAULT_TOOLSETS``);
``--toolsets all`` lists every tool.

One route, one tool. The few hand-written tools left here are kept only where they do something
a single route does not (each says what, and names its routes); ``OPERATOR_ALIASES`` keeps the
names an existing agent configuration calls, pointing at the generated tool for the same route.

Reads use the default client; mutations use the agent account when one exists
(``_mutating_client``), so the audit log names the agent. A refused call returns the engine's
status and detail as an MCP tool error, never an empty result.

Usage::

    python -m fichero_mcp.server [--api-url URL] [--library-path PATH] [--toolsets TAG,TAG|all]

The console entry point ``fichero-mcp = "fichero_mcp.server:main"`` is declared
in pyproject.toml. Configuration falls back to the environment
(``FICHERO_API_URL``, ``FICHERO_LIBRARY_PATH``, ``FICHERO_API_KEY``) — the same
variables the CLI honours.
"""

