@mcp.tool()
def fichero_health() -> Any:
    """Check that the Fichero backend is reachable.

    Routes: GET /api/health (a probe the generated surfaces leave out).
    """
    with _client() as client:
        return client.health()


@mcp.tool()
def fichero_use_library(path: str) -> Any:
    """Scope this MCP session to one library by its .fichero path.

    Every subsequent library-scoped tool (docs, search, workflows, KG, …)
    uses it. Without this, tools answer 400 asking for a library — the
    server binds NO library by default (Daniel, 2026-08-27: one server,
    all libraries).

    Kept (#5453): it sets this session's library, which no route does.
    Routes: GET /api/documents (a one-row probe that proves the choice).
    """
    _CONFIG["library_path"] = path
    with _client() as client:
        # Prove the choice immediately instead of deferring the failure to
        # the next tool call.
        client.request("GET", "/api/documents", params={"limit": 1})
    return {"library_path": path, "status": "selected"}


@mcp.tool()
def fichero_docs_list(
    parent_id: Optional[str] = None,
    doc_type: Optional[str] = None,
    file_type: Optional[str] = None,
    status: Optional[str] = None,
    limit: Optional[int] = None,
    offset: int = 0,
) -> Any:
    """List documents in the library, optionally filtered.

    Returns lean summaries (id, name, kind, type, status, child_count) — a
    full document dump made a 92-file folder listing 186KB, which forced
    silly limits (Daniel, 2026-08-27: "why is 50 limit?"). Use
    ``fichero_docs_get`` for one document's full record.

    Kept (#5453): the lean shape (``KEPT_SINGLE_ROUTE``).
    Routes: GET /api/documents.
    """
    with _client() as client:
        result = client.list_documents(
            parent_id=parent_id,
            doc_type=doc_type,
            file_type=file_type,
            status=status,
            limit=limit,
            offset=offset,
        )
    docs = result.get("documents") if isinstance(result, dict) else result
    keep = (
        "id", "parent_id", "name", "node_kind", "doc_type", "file_type",
        "status", "sequence", "child_count", "date_original",
    )

    def slim(doc: Any) -> dict:
        record = doc if isinstance(doc, dict) else doc.model_dump()
        return {k: record.get(k) for k in keep if record.get(k) is not None}

    return [slim(d) for d in (docs or [])]


@mcp.tool()
def fichero_workflow_list() -> Any:
    """List available workflows.

    Each entry carries the engine's own run eligibility (#3804):
    ``direct_runnable`` false means it is an internal component that only runs
    inside a parent workflow — ``fichero_workflow_run`` will refuse it — and
    ``requires_vision`` true means the run needs a vision-capable model.
    Read these; do not infer them from the node list.

    Returns lean summaries (id, name, description, eligibility) — the full
    node/edge dump made the listing 450KB.

    Kept (#5453): the lean shape (``KEPT_SINGLE_ROUTE``).
    Routes: GET /api/workflows.
    """
    with _client() as client:
        result = client.list_workflows()
    items = result.get("workflows") if isinstance(result, dict) else result
    keep = (
        "id", "name", "description", "folder_path", "tags",
        "direct_runnable", "requires_vision", "is_system",
    )

    def slim(wf: Any) -> dict:
        record = wf if isinstance(wf, dict) else wf.model_dump()
        return {k: record.get(k) for k in keep if record.get(k) is not None}

    return [slim(w) for w in (items or [])]


@mcp.tool()
def fichero_page_import(
    doc_id: str,
    path: str,
    format: str | None = None,
    name: str | None = None,
) -> Any:
    """Import a PAGE XML, ALTO, hOCR, TEI or YOLO file as a NEW PASS on one page.

    The other direction of `fichero_page_export`. Not `fichero_documents_import_file`, which puts a
    new document in the library: this adds somebody else's transcription of a page that
    is already there.

    Returns the new `pass_id`, the format that was RECOGNISED (which may not be what the
    file's name claimed — a renamed eScriptorium export still reads as `pagexml`), the
    counts that landed (`segments`, `readings`, `order_entries`), the file's `checksum`,
    and `geometry_problems`: how many shapes the file could not express properly and the
    engine repaired. For a multi-page TEI file, `pages_in_file` and `pages_left_out` name the
    pages that did NOT become this pass. **Report the recognised format, any repairs and any
    pages left out to the person.** An
    import described as clean when forty boxes were repaired is a confident wrong answer.

    The import does NOT become the working pass. Somebody else's file arriving is not a
    decision about which reading of the page is authoritative, so nothing already on the
    page changes.

    Refusals carry the sentence that matters: the same bytes already on this document
    (nothing was written, and the sentence names the pass that holds them), a file nothing
    recognises (the sentence lists the formats this build reads), or shapes lying outside
    the page the file declares (the sentence names the segments that disagree). Pass the
    sentence on rather than reporting that the import failed.

    Args:
        doc_id: The page's document id.
        path: Path to the interchange file on the machine THIS MCP server runs on. Its
            bytes are uploaded (for YOLO, with the classes.txt or data.yaml found beside
            it), so the engine may be remote.
        format: Force a format instead of recognising one from the bytes.
        name: What to call the new pass.

    Kept (#5453): the YOLO dataset file found beside the labels (``KEPT_SINGLE_ROUTE``).
    Routes: POST /api/documents/{doc_id}/import.
    """
    with _mutating_client() as client:
        return client.import_page(doc_id, path, import_format=format, name=name)


