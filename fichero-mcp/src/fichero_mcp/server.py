def _client() -> FicheroClient:
    """Build a client from the server config (env-discovered when unset).

    The tools below use this synchronous client directly on the event loop.
    That is sound because this server only runs over stdio (see ``main``),
    where MCP dispatches one request at a time — there is no concurrency to
    block. A non-stdio transport would need an async client instead.
    """
    return FicheroClient(
        base_url=_CONFIG["base_url"],
        library_path=_CONFIG["library_path"],
        client_name="fichero-mcp",
    )


def _agent_client() -> FicheroClient:
    """Build the dedicated agent-account client for audited MCP mutations.

    Fail closed BEFORE any connection: building a client may dial the engine (to read its
    certificate), so an agent with no stored session must be refused first. Otherwise the
    refusal depends on whether an engine happens to be listening.
    """
    from fichero_cli import client as client_module

    if not client_module._read_token(as_user="agent"):
        raise RuntimeError("No stored session for agent; run `fichero auth login agent`.")
    client = FicheroClient(
        base_url=_CONFIG["base_url"],
        library_path=_CONFIG["library_path"],
        as_user="agent",
        client_name="fichero-mcp",
    )
    if not client.token:
        client.close()
        raise RuntimeError("No stored session for agent; run `fichero auth login agent`.")
    return client


def _mutating_client() -> FicheroClient:
    """Client for MUTATING tools: the agent account when one exists (#4469).

    With a stored agent session (`fichero auth login agent`, multiuser), the
    mutation is the agent's — actor "agent" in the audit. Without one
    (single-user engines have no accounts), the owner credential acts, and the
    X-Fichero-Client tag both clients send keeps the audit row truthful about
    WHICH surface used it: actor=owner, client=fichero-mcp — recorded, not
    silent.
    """
    try:
        return _agent_client()
    except RuntimeError:
        return _client()


# Late-bound, so a test that patches `_client` / `_mutating_client` patches the generated tools too.
openapi_runtime.configure(lambda: _client(), lambda: _mutating_client())

_BY_ROUTE = {(tool.method, tool.path): tool for tool in TOOLS}
_SELECTED: list[str] = []


def parse_toolsets(value: str | Iterable[str]) -> tuple[str, ...]:
    """Tags from ``--toolsets`` (a comma list, or ``all``); an unknown tag is an error naming the known."""
    names = [v.strip() for v in (value.split(",") if isinstance(value, str) else value) if v.strip()]
    if names == ["all"]:
        return TAGS
    unknown = sorted(set(names) - set(TAGS))
    if unknown:
        raise ValueError(f"unknown toolsets {unknown}; known: {', '.join(TAGS)} (or all)")
    return tuple(names)


def select_toolsets(toolsets: Iterable[str], server: FastMCP | None = None) -> list[str]:
    """Register the generated tools of ``toolsets`` (and the operator aliases) on ``server``.

    Replaces whatever an earlier call registered, so ``main`` can narrow or widen the default.
    Returns the names registered.
    """
    server = server or mcp
    if server is mcp:
        for name in _SELECTED:
            server.remove_tool(name)
        _SELECTED.clear()
    chosen = set(toolsets)
    names: list[str] = []
    for tool in TOOLS:
        if tool.tag in chosen:
            server.add_tool(tool.fn, name=tool.name)
            names.append(tool.name)
    hand_written = {t.name for t in server._tool_manager.list_tools()}
    for alias, route in OPERATOR_ALIASES.items():
        if alias not in hand_written:
            target = _BY_ROUTE[route]
            server.add_tool(target.fn, name=alias, description=f"Alias of `{target.name}`.\n\n{target.fn.__doc__}")
            names.append(alias)
    if server is mcp:
        _SELECTED.extend(names)
    return names


