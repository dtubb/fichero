"""Every persisted id field, and what a transfer between projects does with it (#5657).

The source of truth for the id map in `docs/contributor_manual/specs/source/moving-between-projects.md`
("The id map"). `tests/unit/transfer/test_every_id_field_is_classified.py` enumerates every persisted
model (`Database._all_schema_models`, nested models included), every raw-SQL table's columns, and the
keys the correction-episode ledger writes, and fails when an id field is missing here — so the next
table cannot be forgotten by the transfer. To fix that failure: add the field below, in ONE bucket,
with a one-line reason.

Keys:

- ``"Model.field"`` — a pydantic model field. For a nested model (a ``SourceAnchor`` inside a
  segment, a ``SourceSupport`` inside a claim) the key names the nested class, and the field follows
  the row that holds it.
- ``"table:<name>.<column>"`` — a column of a table created by hand-written SQL.
- ``"episodes:<path>"`` — a key in the correction-episode ledger, `<package>/episodes/YYYY-MM.jsonl`
  (`observability/episodes.py`), dotted from the record's top.

Buckets:

- ``MAPPED`` — the row travels with the page; the id is re-pointed through the transfer's id map.
  The universal rule applies: when the id it names stays behind (outside the set), that edge is
  CUT and listed, never written into the target.
- ``CUT`` — the row stays in the source (it belongs to something that does not travel); when the id
  names a moved item, that entry is cut in the source on a move and listed in the result.
- ``RECOMPUTED`` — a derived id: computed again in the target (from a new artifact id, a new
  folder/item pair, a fresh pair key, the transfer's own audit row), never mapped as a string.
- ``PROJECT_VOCAB`` — names a per-project vocabulary record (a hand, an allograph, a declared sign,
  a framework, a bibliography entry): matched by key in the target, made there if missing.
- ``NOT_DOCUMENT_SCOPED`` — names something that is not a row of the moved set: an app- or
  engine-wide record, a person, an external identifier, or the source's own history (runs, audit
  chain, undo log). Never re-pointed; where the row travels the value is kept as text naming the
  source project.
"""

