def nav_block(presets: list[dict[str, Any]], tools: list[Any]) -> str:
    """The mkdocs nav lines for the generated reference, marker to marker."""
    lines = [
        NAV_BEGIN,
        "      - Reference:",
        "          - Workflows & Tools: user/reference/index.md",
        "          - Workflows:",
        "              - Every Workflow: user/reference/workflows/index.md",
    ]
    for preset in sorted(presets, key=lambda p: p["name"]):
        page = f"user/reference/workflows/{slugify(preset['name'])}.md"
        lines.append(f"              - {preset['name']}: {page}")
    lines += [
        "          - Tools:",
        "              - Every Tool: user/reference/tools/index.md",
    ]
    for tool in sorted(tools, key=lambda t: (t.display_name, t.name)):
        lines.append(f"              - {tool.display_name}: user/reference/tools/{tool.name}.md")
    lines.append(NAV_END)
    return "\n".join(lines) + "\n"


def patch_mkdocs(block: str) -> bool:
    """Replace the marked nav region in mkdocs.yml. Returns True if it changed."""
    text = MKDOCS.read_text()
    if NAV_BEGIN not in text or NAV_END not in text:
        raise SystemExit(
            f"mkdocs.yml has no capability-reference nav markers.\n"
            f"  Add these two lines inside the User Guide nav section:\n"
            f"{NAV_BEGIN}\n{NAV_END}"
        )
    start = text.index(NAV_BEGIN)
    end = text.index(NAV_END) + len(NAV_END) + 1
    updated = text[:start] + block + text[end:]
    if updated == text:
        return False
    MKDOCS.write_text(updated)
    return True


def committed_nav_block() -> str:
    """What mkdocs.yml currently holds between the markers."""
    text = MKDOCS.read_text()
    if NAV_BEGIN not in text or NAV_END not in text:
        return ""
    start = text.index(NAV_BEGIN)
    end = text.index(NAV_END) + len(NAV_END) + 1
    return text[start:end]


