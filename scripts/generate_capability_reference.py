# driver
# --------------------------------------------------------------------------


def generate(out_dir: Path) -> dict[str, int]:
    """Write the whole reference tree. Returns counts of what was written."""
    tools = load_tools()
    presets = load_presets()
    by_name = {tool.name: tool for tool in tools}

    if out_dir.exists():
        shutil.rmtree(out_dir)
    (out_dir / "tools").mkdir(parents=True)
    (out_dir / "workflows").mkdir(parents=True)

    (out_dir / "index.md").write_text(overview_page(presets, tools))
    (out_dir / "tools" / "index.md").write_text(tools_index_page(tools))
    (out_dir / "workflows" / "index.md").write_text(workflows_index_page(presets))
    for tool in tools:
        (out_dir / "tools" / f"{tool.name}.md").write_text(tool_page(tool))
    for preset in presets:
        page = out_dir / "workflows" / f"{slugify(preset['name'])}.md"
        page.write_text(workflow_page(preset, by_name))

    return {"tools": len(tools), "workflows": len(presets)}


def self_test() -> int:
    assert slugify("Capture OCR + Transcribe") == "capture-ocr-transcribe"
    assert cell("a | b") == r"a \| b"
    assert cell(True) == "yes"
    assert cell(None) == "—"
    assert fenced("has ``` inside")[0] == "````text"
    preset = {
        "nodes": [{"id": "c"}, {"id": "a"}, {"id": "b"}],
        "edges": [
            {"source": "a", "target": "b"},
            {"source": "b", "target": "c"},
        ],
    }
    assert [n["id"] for n in run_order(preset)] == ["a", "b", "c"]
    cyclic = {"nodes": [{"id": "x"}, {"id": "y"}], "edges": [
        {"source": "x", "target": "y"},
        {"source": "y", "target": "x"},
    ]}
    assert len(run_order(cyclic)) == 2, "a cycle must not drop steps"
    print("generate_capability_reference self-test passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=None, help="write pages here instead of docs/user/reference")
    parser.add_argument("--print-nav", action="store_true", help="print the mkdocs nav block and exit")
    parser.add_argument("--self-test", action="store_true", help="run the built-in checks")
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    if args.print_nav:
        sys.stdout.write(nav_block(load_presets(), load_tools()))
        return 0

    out_dir = args.out or OUT_DIR
    counts = generate(out_dir)
    print(f"wrote {counts['tools']} tool pages and {counts['workflows']} workflow pages")
    print(f"  into {out_dir}")

    if args.out is None:
        changed = patch_mkdocs(nav_block(load_presets(), load_tools()))
        print("  mkdocs.yml nav " + ("updated" if changed else "already current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
